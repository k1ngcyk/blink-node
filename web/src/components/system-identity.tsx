export function SystemIcon({ os }: { os?: string }) {
  const system = operatingSystem(os);
  const Icon = icons[system as keyof typeof icons] ?? IconDeviceDesktop;
  return (
    <span className={`system-icon os-${system}`} aria-hidden="true">
      {paths[system] ? (
        <svg width="20" height="20" viewBox="0 0 24 24" fill="currentColor">
          <path d={paths[system]} />
        </svg>
      ) : (
        <Icon size={21} stroke={1.7} />
      )}
    </span>
  );
}
export function SystemIdentity({ os, detail }: { os?: string; detail?: string }) {
  return (
    <span className="system-identity">
      <SystemIcon os={os} />
      <span className="min-w-0">
        <span className="system-name">{os || "等待系统信息"}</span>
        {detail && <span className="subline">{detail}</span>}
      </span>
    </span>
  );
}
